/**
 * AI 视频无限画布：项目 / 节点 / 执行事件共享类型。
 * 与现有 Dashscope video-tools、Remotion 管线独立。
 */

/** 视觉底座类型：文本不展示图片缩略图 */
export type AiVideoNodeBaseType = 'text' | 'image' | 'video'

/** 业务语义（同类底座可对应多种 kind） */
export type AiVideoNodeKind =
  | 'screenwriter'
  | 'script_text'
  | 'character'
  | 'character_views'
  | 'scene'
  | 'prop'
  | 'storyboard'
  | 'storyboard_text'
  | 'video_gen'
  | 'video_merge'

/** 节点执行态 */
export type AiVideoNodeStatus = 'idle' | 'running' | 'success' | 'error'

/** 节点产物：文本或本地媒体路径 */
export interface AiVideoNodeResult {
  text?: string
  localPath?: string
  mediaType?: 'image' | 'video' | 'text'
}

export interface AiVideoCanvasNode {
  id: string
  /** 展示标题 */
  title: string
  type: AiVideoNodeBaseType
  kind: AiVideoNodeKind
  position: { x: number; y: number }
  /** 用户/编剧生成的提示词或大纲 */
  prompt: string
  /** 用户手动覆盖的提示词（优先于 prompt） */
  manualPrompt?: string
  /** workflows-api 相对路径，如 blueprints/Text to Image (Z-Image-Turbo).json */
  workflowId?: string
  /** 节点级 skill id */
  skillIds?: string[]
  status: AiVideoNodeStatus
  errorMessage?: string
  result?: AiVideoNodeResult
  /**
   * @ 引用的上游节点 id。
   * 必须是已连线且 kind ∈ character_views | scene | prop 的节点。
   */
  refs?: string[]
  /** 是否由编剧自动生成（幂等扩图时用于对齐） */
  autoGenerated?: boolean
  /** 自动扩图对齐键，如 character:张三 */
  autoKey?: string
}

export interface AiVideoCanvasEdge {
  id: string
  source: string
  target: string
}

export interface AiVideoCanvasViewport {
  x: number
  y: number
  zoom: number
}

export interface AiVideoCanvasState {
  nodes: AiVideoCanvasNode[]
  edges: AiVideoCanvasEdge[]
  viewport?: AiVideoCanvasViewport
}

export interface AiVideoProject {
  id: string
  title: string
  /** 列表卡片缩略图本地路径 */
  thumbnailPath?: string
  createdAt: number
  updatedAt: number
  /** 画布全局 skill，对所有节点 LLM/执行生效 */
  globalSkillIds: string[]
  canvas: AiVideoCanvasState
}

/** 列表摘要（不含完整画布，减少 IPC 体积时可扩展；当前仍返回完整项目） */
export type AiVideoProjectSummary = Pick<
  AiVideoProject,
  'id' | 'title' | 'thumbnailPath' | 'createdAt' | 'updatedAt'
>

