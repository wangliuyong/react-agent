/** kind → 默认底座类型 */
export function queryAiVideoBaseType(kind: AiVideoNodeKind): AiVideoNodeBaseType {
  if (
    kind === 'screenwriter' ||
    kind === 'script_text' ||
    kind === 'storyboard_text'
  ) {
    return 'text'
  }
  if (kind === 'video_gen' || kind === 'video_merge') {
    return 'video'
  }
  return 'image'
}

/** kind → 默认 workflow */
export function queryAiVideoDefaultWorkflow(kind: AiVideoNodeKind): string | undefined {
  switch (kind) {
    case 'character':
    case 'scene':
    case 'prop':
      return AI_VIDEO_DEFAULT_WORKFLOWS.textToImage
    case 'character_views':
      return AI_VIDEO_DEFAULT_WORKFLOWS.imageToImage
    case 'storyboard':
      return AI_VIDEO_DEFAULT_WORKFLOWS.storyboard
    case 'video_gen':
      return AI_VIDEO_DEFAULT_WORKFLOWS.videoR2v
    case 'video_merge':
      return AI_VIDEO_DEFAULT_WORKFLOWS.mergeVideos
    default:
      return undefined
  }
}

/**
 * 各节点执行时必须参考的上游 kind。
 * - 三视图 ← 定妆
 * - 分镜 ← 三视图 / 场景 / 道具
 * - 分镜视频 ← 分镜图
 */
export function queryAiVideoRequiredRefKinds(kind: AiVideoNodeKind): AiVideoNodeKind[] {
  switch (kind) {
    case 'character_views':
      return ['character']
    case 'storyboard':
      return ['character_views', 'scene', 'prop']
    case 'video_gen':
      return ['storyboard']
    default:
      return []
  }
}

